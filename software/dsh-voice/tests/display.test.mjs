const store = device => ({ get: () => ({ device: { endpoint: device.endpoint, token: device.token } }) });
test('RGB565按行高字节先发送：红绿蓝白黑与低位量化；候选屏幕偏移/旋转严格验证', () => {
  const rgba = [255,0,0,255, 0,255,0,255, 0,0,255,255, 255,255,255,255, 0,0,0,255, 7,3,7,255];
  assert.deepEqual([...rgb565be(rgba)], [0xf8,0, 7,0xe0, 0,31, 255,255, 0,0, 0,0]);
  assert.throws(() => rgb565be([1,2,3]));
  assert.equal(displayConfig().width, 128); assert.equal(displayConfig({ swapXY: true }).width, 160);
  assert.equal(displayConfig({ xGap: 2, yGap: 1 }).height, 160);
  assert.throws(() => displayConfig({ xGap: 5 }), /偏移/);
  assert.throws(() => displayConfig({ swapXY: true, yGap: 5 }), /偏移/);
  assert.throws(() => displayConfig({ profile: 'wrong' }), /型号/);
  assert.throws(() => displayConfig({ bgr: 1 }), /开关/);
  assert.throws(() => displayConfig({ pins: [1,2,3] }), /配置/);
});
test('真实HTTP显示握手/鉴权/大帧传输：只返回queued，不假称实际显示；停旧流不误停新流', async t => {
  const device = await displayDevice(); t.after(() => device.close());
  const display = new DisplayService(store(device)); t.after(() => display.dispose());
  const started = await display.start('window', { profile: 'st7789-240x320' });
  assert.equal(started.width, 240); assert.equal(started.height, 320);
  const pixels = Buffer.alloc(MAX_FRAME_BYTES, 0xf8);
  assert.equal((await display.frame('window', started.streamId, 1, pixels)).state, 'queued');
  assert.deepEqual(device.frames[0], pixels); assert.equal(device.state.drawn, 0);
  await assert.rejects(display.frame('window', started.streamId, 1, pixels), /序号/);
  await assert.rejects(display.frame('other', started.streamId, 2, pixels), /失效/);
  await assert.rejects(display.frame('window', started.streamId, 2, pixels.subarray(2)), /长度/);
  await assert.rejects(display.start('other', {}), /占用/);
  await display.stop('other', started.streamId); assert.equal(device.state.streamId, started.streamId);
  await display.stop('window', started.streamId);
  const next = await display.start('window', {});
  await display.stop('window', started.streamId); assert.equal(device.state.streamId, next.streamId);
  assert.equal(device.receivedHeaders[0].authorization, 'Bearer screen-test-token');
  assert.equal(JSON.stringify(started).includes('screen-test-token'), false);
});
test('拒绝旧固件/坏确认/错误Token；上一帧未完成时不积压，停止取消在途帧', async t => {
  const legacy = await displayDevice({ legacy: true }); t.after(() => legacy.close());
  await assert.rejects(new DisplayService(store(legacy)).start('window', {}), /M3/);
  assert.equal(legacy.commands.length, 0);
  const wrong = await displayDevice({ wrongAck: true }); t.after(() => wrong.close());
  const bad = new DisplayService(store(wrong)); t.after(() => bad.dispose());
  const s = await bad.start('window', {});
  await assert.rejects(bad.frame('window', s.streamId, 1, Buffer.alloc(40960)), /未确认/);
  await assert.rejects(new DisplayService(store({ endpoint: wrong.endpoint, token: 'wrong' })).info(), /401/);
  const slow = await displayDevice({ delay: 120 }); t.after(() => slow.close());
  const display = new DisplayService(store(slow)); t.after(() => display.dispose());
  const started = await display.start('window', {});
  const pending = display.frame('window', started.streamId, 1, Buffer.alloc(40960));
  const rejected = assert.rejects(pending, /失败|停止/);
  await assert.rejects(display.frame('window', started.streamId, 2, Buffer.alloc(40960)), /上一帧/);
  await display.stop('window', started.streamId); await rejected;
});
test('电脑API转发153600字节帧、拒绝越界和伪序号，屏幕配置独立持久化', async t => {
  const device = await displayDevice(); t.after(() => device.close());
  const dataDir = mkdtempSync(join(tmpdir(), 'lease-display-api-'));
  const preview = await createPreview({ dataDir, mediaOptions: { home: join(dataDir, 'empty') } }); t.after(() => preview.close());
  preview.store.save({ device: { endpoint: device.endpoint, token: device.token } });
  const root = `${preview.url}/api/lease-voice`;
  const post = (path, body) => fetch(`${root}/${path}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const result = await (await post('screen-control', { action: 'start', clientId: 'window', config: { profile: 'st7789-240x320' } })).json();
  assert.ok(result.streamId);
  const headers = { 'Content-Type': 'application/octet-stream', 'X-Lease-Client-Id': 'window', 'X-Lease-Stream-Id': result.streamId, 'X-Lease-Sequence': '1' };
  const frame = await fetch(`${root}/screen-frame`, { method: 'POST', headers, body: Buffer.alloc(MAX_FRAME_BYTES) });
  assert.equal(frame.status, 202); assert.equal(device.frames[0].length, MAX_FRAME_BYTES);
  const invalid = await fetch(`${root}/screen-frame`, { method: 'POST', headers: { ...headers, 'X-Lease-Sequence': '-1' }, body: Buffer.alloc(1) });
  assert.equal(invalid.status, 400);
  const handler = createHandler({ display: preview.display });
  assert.equal((await handler(new Request(`${root}/screen-frame`, { method: 'POST', headers, body: Buffer.alloc(MAX_FRAME_BYTES + 1) }))).status, 413);
  assert.equal((await post('media', { display: { xGap: 2, yGap: 1, bgr: true } })).status, 200);
  assert.equal((await (await fetch(`${root}/media`)).json()).display.bgr, true);
});
